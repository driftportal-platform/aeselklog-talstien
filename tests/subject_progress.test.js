const assert=require('node:assert/strict');
const P=require('../adaptive.js'),G=require('../savegame.js');
const source=P.freshProgress();
assert.deepEqual(Object.keys(source.areas).sort(),['minus','numbers','plus','tables']);
let x=source;
for(let i=0;i<3;i++)x=P.noteArea(x,'plus',true).state;
assert.equal(x.areas.plus.step,1);
assert.equal(x.areas.minus.step,0);
assert.equal(x.areas.tables.step,0);
assert.equal(x.areas.numbers.step,0);
for(let i=0;i<2;i++)x=P.noteArea(x,'minus',false).state;
assert.equal(x.areas.minus.step,-1);
assert.equal(x.areas.plus.step,1);
x=P.noteArea(x,'tables',true,{helped:true}).state;
assert.equal(x.areas.tables.rightStreak,0,'Tips may not increase independent right streaks');
assert.equal(x.areas.tables.correct,1);
assert.equal(x.areas.numbers.attempted,0);
assert.equal(x.attempted,6);
const older=P.cleanProgress({step:2,rightStreak:1,attempted:10,correct:8});
assert.equal(older.areas.plus.step,2);
assert.equal(older.areas.tables.step,2);
assert.equal(older.areas.tables.attempted,0,'Old global totals cannot be assigned to a subject');
assert.equal(P.challengeArea({type:6,question:'Hvad er 3 × 5?'}),'tables');
assert.equal(P.challengeArea({type:6,question:'Hvad er 7 + 5?'}),'plus');
assert.equal(P.challengeArea({type:6,question:'Hvad er 10 − 5?'}),'minus');
assert.equal(P.challengeArea({type:2,question:'Er resultatet af 7 + 5 lige eller ulige?'}),'numbers');
assert.equal(P.challengeArea({type:6,skillArea:'plus',question:'Hvad er 5 + 5?'}),'plus');
const old={schema:1,config:{raw:'1-100',learning:'udfordring',moveDice:'physical'},players:[{id:'player1',name:'Barn',kind:'child',age:8,pos:5,learning:{step:1,rightStreak:1,attempted:8,correct:5}}],turn:0,phase:'question',pending:{from:2,roll:3,landing:5,target:5},challenge:{type:6,question:'Hvad er 2 + 4?',correct:'6',options:['6','7','8']}};
const migrated=G.normalize(old);
assert(migrated,'v0.9.9 snapshot must remain readable');
assert.equal(migrated.schema,1);
assert.equal(migrated.players[0].learning.areas.plus.step,1);
assert.equal(migrated.challenge.exerciseId,'');
assert.equal(P.challengeArea(migrated.challenge),'plus');
let l=P.noteArea(P.cleanProgress(migrated.players[0].learning),'plus',true).state;
assert.equal(l.areas.plus.step,1);
assert.equal(l.areas.minus.attempted,0);
const newer={...old,players:[{...old.players[0],learning:x}],challenge:{...old.challenge,skillArea:'plus',exerciseId:'q123_456'}};
const saved=G.normalize(newer);
assert.equal(saved.challenge.skillArea,'plus');
assert.equal(saved.challenge.exerciseId,'q123_456');
assert.equal(saved.players[0].learning.areas.minus.step,-1);
assert.equal(saved.players[0].learning.areas.plus.step,1);
console.log('PASS: independent plus/minus/tables/numbers, helped answers, legacy save migration and subject-aware challenges');
